#!/usr/bin/env python3
"""Revision-3 experiment matrix: the matrix of run_rev1.py with the degree-aware probe/scan test as the default
of AZX, plus group 'abl': AZX, AZX-NODEG (the test without deg+(u), an index of its own) and BFS in one process,
with AZX and AZX-NODEG swapping timing positions on odd updates. Every table is regenerated by ONE binary
(code/authz, built from code/authz.cpp with -DAUTHZ_SRC_HASH).
Outputs go to results_rev3/<group>/<name>.txt.

usage: run_rev3.py <root> [jobs]      (root holds code/ and data/; run on the server)
"""
import os, subprocess, sys, time
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.abspath(sys.argv[1]); JOBS = int(sys.argv[2]) if len(sys.argv) > 2 else 8
BIN = f'{ROOT}/code/authz'
OUTDIR = os.environ.get('AUTHZ_OUTDIR', 'results_rev3')
FAST = 'AZX,BFS,SPICE-ML,SPICE-FC,CLOSURE,DEFER-SAFE,DEFER-NAIVE'
ABL = 'AZX,AZX-NODEG,BFS'
HEAVY = 'AZX,BFS,TC,PLL,LCR'
SV = 'AZX,BFS,SV-DTC,SV-DTC-deg5,SV-DTC-deg64'
DATA = ['ent', 'syn10k', 'amzn', 'youtube', 'dblp', 'deep_L8', 'deep_L12', 'deep_L16', 'syn100k', 'syn1m', 'lj',
        'real_go', 'real_hpo', 'real_simplewiki', 'real_go_m4', 'real_hpo_m4', 'real_simplewiki_m4', 'real_enwiki', 'deep1m_L12', 'deep1m_L16', 'lj_full', 'orkut', 'friendster', 'syn10m']
BIG = {'syn1m', 'lj', 'deep1m_L12', 'deep1m_L16', 'lj_full', 'orkut', 'friendster', 'real_enwiki', 'syn10m'}
NO_TC = {'deep_L16', 'deep1m_L12', 'deep1m_L16', 'lj_full', 'orkut', 'friendster', 'syn1m', 'real_enwiki', 'syn10m'}

jobs = []
def job(group, name, ds, methods, qpu=10, nupd=-1, seed=1, W=100, B=1000, K=64, env=None, timeout=7200):
    if os.path.isdir(f'{ROOT}/data/{ds}'):
        jobs.append((group, name, ds, methods, qpu, nupd, seed, W, B, K, env or {}, timeout))

D64 = {'AUTHZ_DEFER_B': '64'}
for ds in DATA:
    for seed in ([1] if ds in BIG else [1, 2, 3]):
        job('main', f'{ds}_s{seed}', ds, FAST, seed=seed, env=D64)
        job('abl', f'{ds}_s{seed}', ds, ABL, seed=seed, env=D64)
    hv = HEAVY.replace(',TC', '') if ds in NO_TC else HEAVY
    job('heavy', ds, ds, hv, nupd=100 if ds in BIG or ds.startswith('deep_L1') else 1000, env=D64)
    if ds == 'syn1m':
        job('heavy', 'syn1m_TC', ds, 'AZX,TC', nupd=50, env=D64, timeout=10800)
    job('main_sv', f'{ds}_s1', ds, SV, env=D64)
for ds in ['ent', 'syn100k', 'amzn']:
    for W in [10, 100, 1000]:
        job('sweep_spice', f'{ds}_W{W}', ds, 'BFS,SPICE-ML', W=W, nupd=5000)
    for Bd in [16, 64, 256, 1024]:
        job('sweep_defer', f'{ds}_B{Bd}', ds, 'AZX,DEFER-SAFE,DEFER-NAIVE', nupd=5000, env={'AUTHZ_DEFER_B': str(Bd)})
for L in [2, 4, 8, 12, 16]:
    for seed in [1, 2, 3]:
        job('sweep_depth', f'deep_L{L}_s{seed}', f'deep_L{L}', 'AZX,BFS,CLOSURE', nupd=2000, seed=seed)
# read/write ratio: checks per update (99:1 is the Zanzibar figure)
for ds in ['ent', 'syn100k', 'deep_L16', 'amzn']:
    for q in [10, 100, 1000]:
        job('sweep_ratio', f'{ds}_q{q}', ds, 'AZX,BFS,SPICE-ML,DEFER-SAFE,DEFER-NAIVE', qpu=q,
            nupd={10: 5000, 100: 2000, 1000: 300}[q], env=D64)
# expensive index application (replica apply latency): synchronous vs safe deferral with background flush
for ds in ['syn100k', 'deep_L12']:
    for c in [10, 100]:
        job('sweep_apply', f'{ds}_c{c}', ds, 'AZX,DEFER-SAFE', nupd=3000,
            env={'AUTHZ_DEFER_B': '64', 'AUTHZ_APPLY_COST_US': str(c), 'AUTHZ_BG_FLUSH': '1'})

# probe/scan ablation of the check algorithm
for ds in ['deep_L12', 'deep_L16', 'lj', 'real_hpo']:
    for mode in ['scan', 'probe']:
        job('sweep_mode', f'{ds}_{mode}', ds, 'AZX,BFS', nupd=2000, env={'AUTHZ_FORCE_MODE': mode})
    job('sweep_mode', f'{ds}_auto', ds, 'AZX,BFS', nupd=2000)
# enwiki runs use the exact 128-bit build of the same source (path counts exceed 2^63)
WIDE = {'real_enwiki'}


def run(j):
    group, name, ds, methods, qpu, nupd, seed, W, B, K, env, timeout = j
    os.makedirs(f'{ROOT}/{OUTDIR}/{group}', exist_ok=True)
    out = f'{ROOT}/{OUTDIR}/{group}/{name}.txt'
    if os.path.exists(out) and os.path.getsize(out) > 300 and 'TIMEOUT' not in open(out).read():
        return
    e = dict(os.environ); e.update(env)
    cmd = ['/usr/bin/time', '-v', BIN + ('_wide' if ds in WIDE else ''), f'{ROOT}/data/{ds}', methods, str(qpu), str(nupd), str(seed), str(W), str(B), str(K)]
    t0 = time.time()
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, env=e)
        rss = [l for l in r.stderr.splitlines() if 'Maximum resident' in l]
        err = [l for l in r.stderr.splitlines() if l.strip() and 'Command being timed' not in l and ':' not in l[:40]]
        txt = r.stdout + (f'\n# {rss[0].strip()}' if rss else '') + (f'\n# exit={r.returncode}')
    except subprocess.TimeoutExpired as ex:
        txt = (ex.stdout.decode() if isinstance(ex.stdout, bytes) else (ex.stdout or '')) + f'\n# TIMEOUT after {timeout}s'
    txt += f'\n# cmd: {" ".join(cmd[2:])} env={env}\n# wall_s: {time.time() - t0:.1f}\n'
    open(out, 'w').write(txt)
    print(group, name, f'{time.time() - t0:.0f}s', flush=True)


if __name__ == '__main__':
    print(len(jobs), 'jobs', flush=True)
    # big jobs first so they overlap with the many small ones
    jobs.sort(key=lambda j: (j[2] not in BIG, j[0] != 'main'))
    with ThreadPoolExecutor(JOBS) as ex:
        list(ex.map(run, jobs))
    print('ALL DONE', flush=True)
