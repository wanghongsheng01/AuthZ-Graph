#!/usr/bin/env python3
"""Derive code/authz_deg.cpp from code/authz.cpp (which stays unchanged).

The only change: the probe/scan test of the check (Algorithm 2) weighs the grant sources on the
resource side by the user's out-degree, since probe mode tests every source against each of the
user's memberships. Everything else (methods, update loop, probes, oracle, timing, output) is authz.cpp.
"""
import hashlib, os

D = os.path.dirname(os.path.abspath(__file__))
src = open(f'{D}/authz.cpp').read()
base = hashlib.md5(src.encode()).hexdigest()[:12]

test = "(force_mode == 0 && cin * 4 < clab)"
deg = "(force_mode == 0 && cin * G.out[u].size() * 4 < clab)"
pool = "  vector<double> zc(P); { double s = 0; for (int i = 0; i < P; i++) { s += 1.0 / (i + 1); zc[i] = s; } for (auto& z : zc) z /= s; }\n"
tag = pool + '  printf("# deg_mode derived_from=' + base + '\\n");\n'
assert src.count(test) == 1 and src.count(pool) == 1
out = '// GENERATED by code/make_degmode.py from authz.cpp (md5 ' + base + '); do not edit.\n' + src.replace(test, deg).replace(pool, tag)
open(f'{D}/authz_deg.cpp', 'w').write(out)
print('wrote code/authz_deg.cpp from authz.cpp', base)
