#!/usr/bin/env python3
"""Derive code/erp_replay.cpp from code/authz.cpp (which stays unchanged).

The only change: the checks that are not new-enemy probes follow the real page-access trace
(<data>/qtrace.bin: user, resource, hits; sampled in proportion to hits, action = view) instead of the
synthetic query pool. Everything else (methods, update loop, probes, oracle, timing, output) is authz.cpp.
"""
import hashlib, os

D = os.path.dirname(os.path.abspath(__file__))
src = open(f'{D}/authz.cpp').read()
base = hashlib.md5(src.encode()).hexdigest()[:12]

pool = "  vector<double> zc(P); { double s = 0; for (int i = 0; i < P; i++) { s += 1.0 / (i + 1); zc[i] = s; } for (auto& z : zc) z /= s; }\n"
trace = pool + """  // ERP replay: checks other than the new-enemy probes follow the real page-access trace, action = view
  auto qt = readbin<int32_t>(dir + "/qtrace.bin"); size_t QT = qt.size() / 3;
  int cview = 0; while (cview < NC - 1 && !(ctx[cview] & 1ULL)) cview++;
  vector<double> qcdf(QT); { double s = 0; for (size_t i = 0; i < QT; i++) { s += qt[3 * i + 2]; qcdf[i] = s; } for (auto& z : qcdf) z /= s; }
  printf("# erp_replay derived_from=%s trace_pairs=%zu\\n", \"""" + base + """\", QT);
"""
pick = "      } else if (U01(rng) < 0.7) { double z = U01(rng); int i = (int)(lower_bound(zc.begin(), zc.end(), z) - zc.begin()); i = min(i, P - 1); u = pool[i][0]; r = pool[i][1]; c = pool[i][2]; }\n      else rand_triple(u, r, c);\n"
real = "      } else { double z = U01(rng); size_t i = lower_bound(qcdf.begin(), qcdf.end(), z) - qcdf.begin(); i = min(i, QT - 1); u = qt[3 * i]; r = qt[3 * i + 1]; c = cview; }\n"
assert src.count(pool) == 1 and src.count(pick) == 1
out = '// GENERATED by code/make_erp_replay.py from authz.cpp (md5 ' + base + '); do not edit.\n' + src.replace(pool, trace).replace(pick, real)
open(f'{D}/erp_replay.cpp', 'w').write(out)
print('wrote code/erp_replay.cpp from authz.cpp', base)
